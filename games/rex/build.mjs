// Bundles the game (three.js included) into one self-contained HTML file for
// the Flutter app: WebViews won't load ES modules from file:// assets, and the
// app shouldn't need a CDN to show Rex.
import { build } from 'esbuild';
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const out = resolve(here, '../../assets/rex/index.html');

const js = (await build({
  entryPoints: [resolve(here, 'src/main.js')],
  bundle: true,
  format: 'iife',
  minify: true,
  target: ['safari15', 'chrome100'],
  write: false,
})).outputFiles[0].text.replace(/<\/script/gi, '<\\/script');

const css = readFileSync(resolve(here, 'styles.css'), 'utf8');
let html = readFileSync(resolve(here, 'index.html'), 'utf8')
  .replace(/<script type="importmap">[\s\S]*?<\/script>\s*/, '')
  .replace(/<link rel="stylesheet" href="styles.css" \/>/, () => `<style>\n${css}</style>`)
  .replace(/<script type="module" src="src\/main.js"><\/script>/, () => `<script>${js}</script>`);

if (html.includes('src/main.js') || html.includes('importmap')) throw new Error('index.html markers changed; update build.mjs');
mkdirSync(dirname(out), { recursive: true });
// Note goes after the doctype so the page stays in standards mode.
html = html.replace('<!doctype html>', '<!doctype html>\n<!-- Generated by games/rex/build.mjs: edit games/rex, then run `npm run build`. -->');
writeFileSync(out, html);
console.log(`wrote ${out} (${(html.length / 1024).toFixed(0)} KB)`);
